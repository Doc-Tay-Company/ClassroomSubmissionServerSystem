const assert = require('assert');
const fs = require('fs');
const vm = require('vm');

let focused = true;
let visibilityState = 'visible';
let id = 0;
const window = { crypto: { randomUUID: () => `uuid-${++id}` } };
const document = { hasFocus: () => focused, get visibilityState() { return visibilityState; } };
vm.runInNewContext(fs.readFileSync('static/js/exam-telemetry.js', 'utf8'), { window, document, Date, Math, Promise });

const posted = [];
let shouldFail = false;
const collector = window.createExamTelemetry({
  sendSnapshot: async () => {},
  submitEvent: async (event) => {
    posted.push(event);
    if (shouldFail) { shouldFail = false; throw new Error('offline'); }
    return { recorded: true };
  },
});
const tick = () => new Promise((resolve) => setImmediate(resolve));

(async () => {
  // An initially hidden/unfocused page establishes a baseline, not an event.
  focused = false;
  visibilityState = 'hidden';
  collector.setActive(true, 'release-A');
  collector.onBlur();
  collector.onVisibilityChange();
  await tick();
  assert.strictEqual(posted.length, 0);

  // One browser action can produce both independent event types.
  focused = true;
  visibilityState = 'visible';
  collector.onFocus();
  collector.onVisibilityChange();
  shouldFail = true;
  focused = false;
  collector.onBlur();
  collector.onBlur(); // repeated same-state notification is ignored
  visibilityState = 'hidden';
  collector.onVisibilityChange();
  await tick();
  const failedRequest = posted.find((event) => event.event_type === 'window_blur');
  assert(failedRequest, 'focus loss is emitted');

  // Retried request keeps the same event identity; accepted events are not regenerated by snapshots.
  collector.onFocus();
  await tick();
  assert(posted.some((event) => event.event_type === 'document_hidden'), 'hidden transition is independent');
  assert(posted.filter((event) => event.event_type === 'window_blur').length >= 2);
  assert.strictEqual(posted.filter((event) => event.event_type === 'window_blur')[0].event_id,
    posted.filter((event) => event.event_type === 'window_blur')[1].event_id);
  collector.sendSnapshot();
  collector.onFocus();
  await tick();
  assert.strictEqual(collector.pendingCount(), 0);

  // A new active attempt resets state and doesn't report the starting baseline.
  collector.setActive(false, null);
  focused = false;
  visibilityState = 'hidden';
  const beforeNewBaseline = posted.length;
  collector.setActive(true, 'release-B');
  collector.onBlur();
  collector.onVisibilityChange();
  await tick();
  assert.strictEqual(posted.length, beforeNewBaseline);
  console.log('Exam telemetry transition tests passed');
})().catch((error) => { console.error(error); process.exitCode = 1; });
